#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# 脚本名称：03_verify_network_ready.sh
# 适用场景：第二章第 3 步，验证 Cilium 接管后网络平面已经恢复
# 执行位置：ops 节点
# ==============================================================================

main() {
  echo "========================================================="
  echo "检查 1：节点状态"
  echo "========================================================="
  kubectl get nodes -o wide

  echo
  echo "========================================================="
  echo "检查 2：kube-system 关键 Pod"
  echo "========================================================="
  kubectl get pods -n kube-system -o wide

  echo
  echo "========================================================="
  echo "检查 3：Cilium 状态"
  echo "========================================================="
  cilium status --wait

  echo
  echo "========================================================="
  echo "检查 4：Hubble 服务"
  echo "========================================================="
  kubectl get svc -n kube-system hubble-relay hubble-ui

  echo
  echo "OK: 第二章网络平面恢复验证通过"
}

if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  main
fi
